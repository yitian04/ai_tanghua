EXECUTION_HELP="""
### 执行参数
| 参数 | 含义 |
|---|---|
| 出料后等待 ms | 打开出料开关后，等待多久再继续运动。 |
| 收料后等待 ms | 关闭出料开关后，等待多久再继续运动。 |
| 转弯圆滑程度 mm | 允许机器人在转角附近平滑通过的程度。0 表示不做圆滑过渡；增大可能偏离原折线。 |
| 指令速度上限 mm/s | 每段指令使用“轨迹目标点速度”和此上限中较小的值。 |
| 加速度 m/s² | 速度变化的快慢；短线段未必达到设置的最高速度。 |

**首版整个任务固定使用 10% 控制器倍率，包括绘制。**例如轨迹速度 30 mm/s、上限 50 mm/s，先得到指令速度 30 mm/s，再受到 10% 倍率、加速度和控制器安全限制影响；不能把 30 mm/s 当作实测速度。

进出路径另用高级设置中的低速参数。延迟只用于执行／机器人程序导出，不写入标准轨迹；素材模拟器不包含这些等待及机器人加减速。

### 两个运行按钮
- **关料试运行**：按照完整路线运动，全程不出料；用于配置验证，不是屏幕模拟。
- **正式绘制**：使用轨迹的出料状态，需已保存并验证当前工作区、路径和接线。

未连接、未记录四角或尚未验证时，页面会列出缺项。保存参数或打开帮助不会连接设备或执行运动。
"""


@st.dialog('操作说明',width='large')
def show_robot_help(topic):
    st.markdown(WORKSPACE_HELP if topic=='workspace' else EXECUTION_HELP)


def help_button(topic):
    if st.button('ⓘ 操作说明',key='robot_help_'+topic,help='工作区示教说明' if topic=='workspace' else '执行参数说明',width='content'):
        show_robot_help(topic)
