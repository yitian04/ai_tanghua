from playwright.sync_api import sync_playwright,expect

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='C:/Program Files/Google/Chrome/Application/chrome.exe',headless=True)
    page=browser.new_page(viewport={'width':1400,'height':1000});page.goto('http://127.0.0.1:8536')
    expect(page.get_by_role('heading',name='AI SVG 曲线',exact=True)).to_be_visible(timeout=20000)
    page.get_by_label('主题与需求',exact=True).fill('一只连续线条的小鸟');page.get_by_label('主题与需求',exact=True).press('Tab')
    page.get_by_label('模型 ID',exact=True).fill('fixture');page.get_by_label('模型 ID',exact=True).press('Enter')
    page.get_by_role('button',name='生成 SVG 曲线',exact=True).click()
    expect(page.get_by_text('SVG 原图',exact=True)).to_be_visible(timeout=20000)
    expect(page.get_by_text('已入库数量：0',exact=True)).to_be_visible()
    page.get_by_role('button',name='保存至素材库',exact=True).click()
    expect(page.get_by_role('dialog')).to_be_visible()
    page.get_by_role('dialog').get_by_role('button',name='取消',exact=True).click()
    expect(page.get_by_text('已入库数量：0',exact=True)).to_be_visible()
    page.get_by_role('button',name='保存至素材库',exact=True).click()
    page.get_by_role('button',name='确认保存 SVG 与曲线',exact=True).click()
    expect(page.get_by_text('已入库数量：2',exact=True)).to_be_visible()
    expect(page.get_by_text('替身生成次数：1',exact=True)).to_be_visible()
    page.set_viewport_size({'width':620,'height':950})
    page.get_by_role('button',name='进入轨迹规划',exact=True).click()
    expect(page.get_by_role('heading',name='轨迹规划',exact=True)).to_be_visible(timeout=15000)
    assert not page.get_by_test_id('stException').count()
    browser.close()
    print('PASS: SVG preview, draft isolation, save cancel/confirm, one request, planning handoff, narrow viewport')
